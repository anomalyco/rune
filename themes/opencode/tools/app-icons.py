#!/usr/bin/env python3
"""Regenerates src/app_icons.rs: the app marks Desktop's Open in menus draw (@opencode/ui's
components/app-icon.tsx, from assets/icons/app), as Rune icons.

usage: tools/app-icons.py <opencode>/packages/ui/src > src/app_icons.rs

Each mark is its SVG's body in a group carrying the root's paint (`fill="none"`), so it draws in
its own colours as the browser does. Named colours are written as #rrggbb, which is how Rune tells
a colour icon from a monochrome one. The PNG marks (Finder, Terminal, TextMate, Warp, Xcode) aren't
icons and stay out.
"""
import re
import sys
from pathlib import Path

# Desktop's ids (app-icon.tsx) and the files they draw; Zed has a dark variant.
FILES = {
    "vscode": "vscode",
    "cursor": "cursor",
    "zed": "zed",
    "zed-dark": "zed-dark",
    "file-explorer": "file-explorer",
    "iterm2": "iterm2",
    "ghostty": "ghostty",
    "android-studio": "android-studio",
    "antigravity": "antigravity",
    "powershell": "powershell",
    "sublime-text": "sublimetext",
}
NAMED = {"white": "#ffffff", "black": "#000000"}


def body(svg):
    root = re.search(r"<svg([^>]*)>", svg)
    inner = svg[root.end():svg.rindex("</svg>")]
    fill = re.search(r'\sfill="([^"]*)"', root.group(1))
    inner = re.sub(r'((?:fill|stroke|stop-color|flood-color)=")(white|black)"', lambda m: m.group(1) + NAMED[m.group(2)] + '"', inner)
    inner = re.sub(r">\s+<", "><", inner.strip())
    inner = re.sub(r"\s+", " ", inner)
    assert '"##' not in inner
    return f'<g fill="{fill.group(1)}">{inner}</g>' if fill else inner


def main():
    src = Path(sys.argv[1]) / "assets" / "icons" / "app"
    print("//! Generated by tools/app-icons.py from @opencode/ui's app marks. Do not edit.")
    print("use rune::Icon;")
    print()
    idents = []
    for name, file in FILES.items():
        svg = (src / f"{file}.svg").read_text()
        view = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', svg)
        assert view and view.group(1) == view.group(2), file
        ident = name.upper().replace("-", "_")
        idents.append((name, ident))
        print(f'static {ident}: Icon = Icon {{ name: "app-{name}", view: {float(view.group(1))}, body: r##"{body(svg)}"## }};')
    print()
    print("/// Desktop's mark for app `id` (`AppIcon`'s ids: \"vscode\", \"file-explorer\", ...), in the")
    print("/// variant for a dark or light appearance; None for the marks Desktop draws from PNGs.")
    print("pub fn named(id: &str, dark: bool) -> Option<&'static Icon> {")
    print("    Some(match id {")
    print('        "zed" if dark => &ZED_DARK,')
    for name, ident in idents:
        if name != "zed-dark":
            print(f'        "{name}" => &{ident},')
    print("        _ => return None,")
    print("    })")
    print("}")


main()
