#!/usr/bin/env python3
"""Regenerates src/file_icons/catalog.rs: @opencode/ui's FileIcon badges (assets/icons/file-types)
for every icon its `chooseIconName` can pick, with that function's name, extension and folder maps.

usage: tools/file-icons.py <opencode>/packages/ui/src > src/file_icons/catalog.rs

Each SVG keeps its own colours, gradients, groups and transforms (Rune draws an icon that names its
colours as full SVG). Presentation attributes on the root move to a group, and a viewBox that doesn't
start at 0 0 becomes a translate.
"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
chooser = (root / "components" / "file-icons" / "choose-icon-name.ts").read_text()
assets = root / "assets" / "icons" / "file-types"


def icon_name(stem):
    # file-icon.tsx's `toIconName`: `folder-src-open` is `FolderSrcOpen`.
    return "".join(w[:1].upper() + w[1:] for w in stem.split("-"))


files = {icon_name(p.stem): p for p in sorted(assets.glob("*.svg"))}


def block(name):
    body = re.search(name + r": \{(.*?)\n  \}", chooser, re.S).group(1)
    pairs = re.findall(r'^\s*(?:"([^"]+)"|([\w@.$-]+)):\s*"(\w+)",', body, re.M)
    # A later duplicate key wins, as in the object literal.
    return list({(q or b): v for q, b, v in pairs}.items())


file_names, extensions, folders = block("fileNames"), block("fileExtensions"), block("folderNames")


def open_variant(name):
    # `toOpenVariant`; a missing variant falls back as FileIcon's failed load does.
    name = name.replace("_light", "Open_light") if name.endswith("_light") else name if name.endswith("Open") else name + "Open"
    return name if name in files else "FolderOpen"


def resolve(name, fallback):
    return name if name in files else fallback


wanted = {"Document", "Folder", "FolderOpen"}
wanted |= {resolve(v, "Document") for _, v in file_names + extensions}
for _, v in folders:
    wanted |= {resolve(v, "Folder"), open_variant(resolve(v, "Folder"))}

DROP = re.compile(r"^(xmlns(:\w+)?|viewBox|width|height|version|class|id|xml:space|data-[\w-]+|aria-[\w-]+|preserveAspectRatio|x|y|enable-background)$")


def body_of(path):
    svg = path.read_text()
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    head, inner = re.search(r"<svg\b([^>]*)>(.*)</svg>", svg, re.S).groups()
    attrs = re.findall(r'([\w:-]+)="([^"]*)"', head)
    x, y, w, h = (float(v) for v in dict(attrs)["viewBox"].replace(",", " ").split())
    assert w == h, f"{path.name}: viewBox is not square"
    inner = re.sub(r"\s+", " ", inner).strip()
    inner = re.sub(r">\s+<", "><", inner)
    kept = " ".join(f'{k}="{v}"' for k, v in attrs if not DROP.match(k))
    if kept:
        inner = f"<g {kept}>{inner}</g>"
    if x or y:
        inner = f'<g transform="translate({-x:g} {-y:g})">{inner}</g>'
    assert '"##' not in inner, f"{path.name}: body would end the raw string"
    return w, inner


def ident(name):
    return re.sub(r"[^A-Z0-9]", "_", files[name].stem.upper())


idents = {}
for name in sorted(wanted):
    assert ident(name) not in idents.values(), f"{name}: identifier collides"
    idents[name] = ident(name)

print("//! Generated by tools/file-icons.py from @opencode/ui's file-type icons and `chooseIconName`. Do not edit.")
print("use rune::Icon;")
print()
for name in sorted(wanted, key=lambda n: idents[n]):
    view, body = body_of(files[name])
    print(f'pub(super) static {idents[name]}: Icon = Icon {{ name: "{files[name].stem}", view: {view:.1f}, body: r##"{body}"## }};')
print()


def lookup(fn, doc, pairs, fallback):
    print(f"/// {doc}")
    print(f"pub(super) fn {fn}(key: &str) -> Option<&'static Icon> {{")
    print("    Some(match key {")
    for k, v in pairs:
        print(f'        "{k}" => &{idents[resolve(v, fallback)]},')
    print("        _ => return None,")
    print("    })")
    print("}")
    print()


lookup("by_file_name", "A whole lower-case file name's badge (`fileNames`).", file_names, "Document")
lookup("by_extension", "A lower-case dotted suffix's badge (`fileExtensions`), `d.ts` as well as `ts`.", extensions, "Document")

print("/// A lower-case folder name's closed and open icons (`folderNames`).")
print("pub(super) fn by_folder_name(key: &str) -> Option<(&'static Icon, &'static Icon)> {")
print("    Some(match key {")
for k, v in folders:
    closed = resolve(v, "Folder")
    print(f'        "{k}" => (&{idents[closed]}, &{idents[open_variant(closed)]}),')
print("        _ => return None,")
print("    })")
print("}")
print()
print("/// Every badge, for a gallery.")
print("pub(super) static ALL: &[&Icon] = &[" + ", ".join(f"&{idents[n]}" for n in sorted(wanted, key=lambda n: idents[n])) + "];")
