#!/usr/bin/env python3
"""Regenerates src/icons.rs: @opencode/ui's artwork and compatibility names in catalog order.

usage: tools/icons.py <opencode>/packages/ui/src/icons > src/icons.rs
"""
import re
import sys
from pathlib import Path

# Card title icons draw at stroke-width 1.5 (card.css); these get a `_BOLD` twin.
BOLD = ["circle-ban-sign", "warning", "circle-check", "help", "dash"]

root = Path(sys.argv[1])
catalog = (root / "catalog.ts").read_text()

icons = {}
for m in re.finditer(r'\n  "?([a-z0-9-]+)"?: \{\s*viewBox: "0 0 (\d+) \d+",\s*body: `([^`]*)`', catalog):
    icons[m.group(1)] = (int(m.group(2)), m.group(3))
alias_block = catalog.split("const aliases = {", 1)[1].split("}", 1)[0]
aliases = dict(re.findall(r'\n  "?([a-z0-9-]+)"?: "([a-z0-9-]+)",', alias_block))

print("//! Generated by tools/icons.py from @opencode/ui's icon catalog. Do not edit.")
print("#![allow(dead_code)]")
print("use rune::Icon;")
for name in [*icons, *aliases]:
    target = aliases.get(name, name)
    view, body = icons[target]
    ident = name.upper().replace("-", "_")
    value = f'..{target.upper().replace("-", "_")}' if name in aliases else f'view: {view}.0, body: r#"{body}"#'
    print(f'pub static {ident}: Icon = Icon {{ name: "{name}", {value} }};')
    if name in BOLD:
        bold = body.replace('stroke="currentColor"', 'stroke="currentColor" stroke-width="1.5"')
        print(f'pub static {ident}_BOLD: Icon = Icon {{ name: "{name}-bold", view: {view}.0, body: r#"{bold}"# }};')
print()
print("/// Every icon by its catalog name, for a gallery or a name read from data.")
print("pub static ALL: &[&Icon] = &[")
for name in [*icons, *aliases]:
    print(f'    &{name.upper().replace("-", "_")},')
print("];")
