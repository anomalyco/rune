#!/usr/bin/env python3
"""Regenerates src/icons.rs: the subset of @opencode/ui's icon catalog the OpenCode theme ships.

usage: tools/icons.py <opencode>/packages/ui/src/icons > src/icons.rs
"""
import re
import sys
from pathlib import Path

NAMES = [
    "plus", "edit", "check", "check-small", "chevron-down", "chevron-right", "close", "xmark-small", "copy",
    "magnifying-glass", "circle-x", "trash", "settings-gear", "arrow-up", "fill-triangle-down", "folder", "help",
    "outline-dots", "branch", "brain", "console", "status", "sidebar", "home", "outline-copy", "save", "cut", "paste",
    "print", "inspect", "warning", "circle-check", "info", "keyboard", "microphone", "globe", "sparkle", "bell",
    "circle-ban-sign", "dash", "subagent", "checklist", "code-lines", "file-tree", "stop", "outline-worktree",
    "grid-plus", "layout-left", "layout-left-full",
]
# Card title icons draw at stroke-width 1.5 (card.css); these get a `_BOLD` twin.
BOLD = ["circle-ban-sign", "warning", "circle-check", "help", "dash"]

root = Path(sys.argv[1])
catalog = (root / "catalog.ts").read_text()
extra = (root / "icon" / "additional-icons.ts").read_text()

primary = {}
for m in re.finditer(r'\n  "?([a-z0-9-]+)"?: \{\s*viewBox: "0 0 (\d+) \d+",\s*body: `([^`]*)`', catalog):
    primary[m.group(1)] = (int(m.group(2)), m.group(3))
additional = {m.group(1): m.group(2) for m in re.finditer(r'\n  "?([a-z0-9-]+)"?: `([^`]*)`', extra)}
small = set(re.findall(r'name === "([a-z0-9-]+)"', extra))

print("//! Generated by tools/icons.py from @opencode/ui's icon catalog. Do not edit.")
print("#![allow(dead_code)]")
print("use rune::Icon;")
for name in NAMES:
    if name in primary:
        view, body = primary[name]
    elif name in additional:
        view, body = (16 if name in small else 20), additional[name]
    else:
        continue
    ident = name.upper().replace("-", "_")
    print(f'pub static {ident}: Icon = Icon {{ name: "{name}", view: {view}.0, body: r#"{body}"# }};')
    if name in BOLD:
        bold = body.replace('stroke="currentColor"', 'stroke="currentColor" stroke-width="1.5"')
        print(f'pub static {ident}_BOLD: Icon = Icon {{ name: "{name}-bold", view: {view}.0, body: r#"{bold}"# }};')
