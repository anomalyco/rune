#!/usr/bin/env python3
"""Regenerates src/tree_icons/catalog.rs: the "complete" file icon set of @pierre/trees, which
Desktop's file trees and file lists draw (gui-plugins `pierre-tree.tsx`, `list.tsx`), with its file
name and extension tokens and each token's light and dark colour.

usage: tools/tree-icons.py <opencode>/node_modules/@pierre/trees/dist > src/tree_icons/catalog.rs

Run `bun install` in the opencode checkout first. The icons are monochrome (`currentColor` with
`opacity` layers). Next.js's fading stroke is a gradient, which a monochrome icon draws solid.
"""
import re
import sys
from pathlib import Path

dist = Path(sys.argv[1])
js = (dist / "builtInIcons.js").read_text()
css = (dist / "style.js").read_text()

symbols = {}
for name, view, body in re.findall(r'<symbol id="([^"]+)" viewBox="0 0 (\d+) \d+">(.*?)</symbol>', js, re.S):
    body = re.sub(r'\s(class)="[^"]*"', "", body)
    body = re.sub(r"\s+", " ", body).strip()
    body = re.sub(r">\s+<", "><", body).replace('"currentcolor"', '"currentColor"')
    symbols[name] = (int(view), body)


def table(name):
    body = re.search(r"const " + name + r" = \{(.*?)\n\};", js, re.S).group(1)
    pairs = re.findall(r'^\s*(?:"([^"]+)"|([\w$-]+)):\s*"([\w-]+)"', body, re.M)
    # Pierre lower-cases names and suffixes before it looks them up, so upper-case keys never match.
    return [(q or b, v) for q, b, v in pairs if (q or b) == (q or b).lower()]


names, extensions, overrides = table("BUILT_IN_FILE_NAME_TOKENS"), table("BUILT_IN_FILE_EXTENSION_TOKENS"), table("COMPLETE_EXTENSION_OVERRIDES")
palette = {k: (light, dark) for k, light, dark in re.findall(r"--trees-icon-(\w+): light-dark\((#\w+), (#\w+)\)", css)}
tints = {t: palette[c] for t, c in re.findall(r"--trees-file-icon-color-([\w-]+): var\(--trees-file-icon-[\w-]+, var\(--trees-icon-(\w+)\)\)", css)}

tokens = sorted({t for _, t in names + extensions + overrides} | {"default"})
for t in tokens:
    assert f"file-tree-builtin-{t}" in symbols, f"no icon for token {t}"


def ident(name):
    return re.sub(r"[^A-Z0-9]", "_", name.upper())


print("//! Generated by tools/tree-icons.py from @pierre/trees's complete icon set. Do not edit.")
print("use rune::Icon;")
print()
for t in tokens:
    view, body = symbols[f"file-tree-builtin-{t}"]
    print(f'static {ident(t)}: Icon = Icon {{ name: "file-tree-{t}", view: {view:.1f}, body: r#"{body}"# }};')
print()
print("/// The icon for a token (`file-tree-builtin-<token>`).")
print("pub(super) fn icon(token: &str) -> &'static Icon {")
print("    match token {")
for t in tokens:
    if t != "default":
        print(f'        "{t}" => &{ident(t)},')
print("        _ => &DEFAULT,")
print("    }")
print("}")
print()


def lookup(fn, doc, pairs):
    print(f"/// {doc}")
    print(f"pub(super) fn {fn}(key: &str) -> Option<&'static str> {{")
    print("    Some(match key {")
    for k, v in dict(pairs).items():
        print(f'        "{k}" => "{v}",')
    print("        _ => return None,")
    print("    })")
    print("}")
    print()


lookup("by_file_name", "A whole lower-case file name's token (`BUILT_IN_FILE_NAME_TOKENS`).", names)
lookup("by_extension", "A lower-case suffix's token (`BUILT_IN_FILE_EXTENSION_TOKENS`).", extensions)
lookup("complete_override", "The complete set's suffix overrides (`COMPLETE_EXTENSION_OVERRIDES`).", overrides)

print("/// A token's colour as `#rrggbb` (light, dark), from `--trees-file-icon-color-<token>`.")
print("pub(super) fn tint(token: &str) -> (&'static str, &'static str) {")
print("    match token {")
for t in tokens:
    if t in tints and t != "default":
        light, dark = tints[t]
        print(f'        "{t}" => ("{light}", "{dark}"),')
light, dark = tints["default"]
print(f'        _ => ("{light}", "{dark}"),')
print("    }")
print("}")
print()
print("/// Every token, for a gallery.")
print("pub(super) const TOKENS: &[&str] = &[" + ", ".join(f'"{t}"' for t in tokens) + "];")
