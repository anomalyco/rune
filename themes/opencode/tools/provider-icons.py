#!/usr/bin/env python3
"""Regenerates src/provider_icons.rs: Desktop's provider marks (@opencode/ui's
assets/icons/provider) for the providers a model list is likely to show, as Rune icons.

usage: tools/provider-icons.py <opencode>/packages/ui/src > src/provider_icons.rs

Rune's icons take one square viewBox from 0 and no transforms, so a mark that needs more is skipped
(a provider without one gets Desktop's `synthetic`).
"""
import re
import sys
from pathlib import Path

NAMES = [
    "opencode", "opencode-go", "anthropic", "openai", "google", "xai", "deepseek", "github-copilot",
    "github-models", "amazon-bedrock", "azure", "mistral", "groq", "cerebras", "moonshotai", "zai",
    "vercel", "fireworks-ai", "togetherai", "perplexity", "synthetic",
]

root = Path(sys.argv[1])

print("//! Generated by tools/provider-icons.py from @opencode/ui's provider marks. Do not edit.")
print("use rune::Icon;")
print()
idents = []
for name in NAMES:
    svg = (root / "assets" / "icons" / "provider" / f"{name}.svg").read_text()
    view = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', svg)
    if not view or view.group(1) != view.group(2) or "transform" in svg:
        print(f"skipped {name}", file=sys.stderr)
        continue
    body = re.sub(r"\s+", " ", re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)).strip()
    ident = name.upper().replace("-", "_")
    idents.append((name, ident))
    print(f'static {ident}: Icon = Icon {{ name: "{name}", view: {float(view.group(1))}, body: r#"{body}"# }};')
print()
print("/// Desktop's mark for provider `id`, if it ships one.")
print("pub fn named(id: &str) -> Option<&'static Icon> {")
print("    Some(match id {")
for name, ident in idents:
    print(f'        "{name}" => &{ident},')
print("        _ => return None,")
print("    })")
print("}")
print()
print("/// The providers that have a mark of their own, in `named`.")
print("pub const NAMES: &[&str] = &[" + ", ".join(f'"{n}"' for n, _ in idents) + "];")
print()
print("/// Desktop's stand-in for a provider with no mark of its own.")
print("pub static FALLBACK: &Icon = &SYNTHETIC;")
